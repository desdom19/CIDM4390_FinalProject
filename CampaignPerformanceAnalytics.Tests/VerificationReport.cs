using System.Globalization;
using System.Text;
using Xunit.Abstractions;

namespace CampaignPerformanceAnalytics.Tests;

/// <summary>
/// Collects actual-against-expected figures from every test and, when the run ends,
/// saves them as a verification report under .scratch/csv-import/.
/// </summary>
/// <remarks>Tests in the "Test database" collection run one at a time, so no locking is needed.</remarks>
public sealed class VerificationReport : IDisposable
{
    private readonly List<TestChecks> _tests = [];

    public TestChecks StartTest(string sourceTicket, string title, ITestOutputHelper output)
    {
        var test = new TestChecks(sourceTicket, title, output);
        _tests.Add(test);
        return test;
    }

    public void Dispose()
    {
        if (_tests.Count == 0)
        {
            return;
        }

        var path = Path.Combine(RepositoryPaths.Root, ".scratch", "csv-import", "verification-report-tests.md");
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, Render());
    }

    private string Render()
    {
        var checks = _tests.SelectMany(t => t.Checks).ToList();
        var failedTests = _tests.Count(t => !t.Passed);

        var report = new StringBuilder();
        report.AppendLine("# Verification report: automated CSV import tests");
        report.AppendLine();
        report.AppendLine($"- Run: {DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture)}");
        report.AppendLine($"- Database: `{TestDatabase.RequiredDatabaseName}` (results and campaigns emptied before each test; Channels untouched)");
        report.AppendLine("- Seam: `CsvImportService.ImportAsync`. Each test feeds a CSV stream and checks the returned `ImportSummary` and the rows in the database.");
        report.AppendLine($"- Tests: {_tests.Count - failedTests} of {_tests.Count} passed");
        report.AppendLine($"- Checks: {checks.Count(c => c.Passed)} of {checks.Count} matched");
        report.AppendLine();
        report.AppendLine("Generated by the test run; do not edit by hand.");

        // xUnit runs tests in random order; list them by the ticket each comes from, then title.
        foreach (var test in _tests.OrderBy(t => t.SourceTicket, StringComparer.Ordinal).ThenBy(t => t.Title, StringComparer.Ordinal))
        {
            report.AppendLine();
            report.AppendLine($"## {test.Title} (from {test.SourceTicket}): {(test.Passed ? "PASS" : "FAIL")}");
            report.AppendLine();
            report.AppendLine("| Check | Expected | Actual | Result |");
            report.AppendLine("|---|---|---|---|");
            foreach (var check in test.Checks)
            {
                report.AppendLine(
                    $"| {Cell(check.Label)} | {Cell(check.Expected)} | {Cell(check.Actual)} | {(check.Passed ? "match" : "**MISMATCH**")} |");
            }
            if (test.Error is not null)
            {
                report.AppendLine();
                report.AppendLine($"Stopped early: {Cell(test.Error)}");
            }
        }
        return report.ToString();

        static string Cell(string text) => text.Replace("|", "\\|").ReplaceLineEndings(" ");
    }
}

/// <summary>
/// The checks of one test. Every check is recorded, matched or not, so the report shows all
/// the actual figures; <see cref="AssertAll"/> then fails the test if any check didn't match.
/// </summary>
/// <param name="sourceTicket">The csv-import ticket whose behaviour the test covers, e.g. "03".</param>
public sealed class TestChecks(string sourceTicket, string title, ITestOutputHelper output)
{
    public record Check(string Label, string Expected, string Actual, bool Passed);

    private readonly List<Check> _checks = [];

    public string SourceTicket { get; } = sourceTicket;
    public string Title { get; } = title;
    public IReadOnlyList<Check> Checks => _checks;
    public string? Error { get; private set; }
    public bool Passed => Error is null && _checks.All(c => c.Passed);

    public void Equal<T>(string label, T expected, T actual) =>
        Record(label, Format(expected), Format(actual), EqualityComparer<T>.Default.Equals(expected, actual));

    /// <summary>Compares two sequences item by item, in order.</summary>
    public void SequenceEqual<T>(string label, IEnumerable<T> expected, IEnumerable<T> actual) =>
        Record(label, Format(expected), Format(actual), expected.SequenceEqual(actual));

    /// <summary>Checks that <paramref name="actual"/> contains every expected fragment, ignoring case.</summary>
    public void Contains(string label, string? actual, params string[] expectedFragments) =>
        Record(label,
            "contains " + string.Join(" and ", expectedFragments.Select(f => $"\"{f}\"")),
            actual is null ? "NULL" : $"\"{actual}\"",
            actual is not null && expectedFragments.All(f => actual.Contains(f, StringComparison.OrdinalIgnoreCase)));

    /// <summary>Records an exception that stopped the test before its checks finished.</summary>
    public void Stopped(Exception exception) => Error = $"{exception.GetType().Name}: {exception.Message}";

    public void AssertAll()
    {
        var mismatches = _checks.Where(c => !c.Passed).ToList();
        Assert.True(mismatches.Count == 0,
            "Mismatched checks:" + Environment.NewLine
            + string.Join(Environment.NewLine, mismatches.Select(c => $"  {c.Label}: expected {c.Expected}, actual {c.Actual}")));
    }

    private void Record(string label, string expected, string actual, bool passed)
    {
        _checks.Add(new Check(label, expected, actual, passed));
        output.WriteLine($"{(passed ? "match   " : "MISMATCH")}  {label}: expected {expected}, actual {actual}");
    }

    // Every value is written culture-independently, so dates always read yyyy-MM-dd.
    private static string Format<T>(T value) => value switch
    {
        null => "NULL",
        DateOnly date => date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
        StoredDailyResult r =>
            $"{Format(r.Date)}: spend {Format(r.Spend)}, impressions {r.Impressions}, clicks {r.Clicks}, "
            + $"leads {r.Leads}, revenue {Format(r.Revenue)}",
        string text => text,
        IFormattable formattable => formattable.ToString(null, CultureInfo.InvariantCulture),
        System.Collections.IEnumerable items => "[" + string.Join(", ", items.Cast<object?>().Select(Format)) + "]",
        _ => value.ToString() ?? "",
    };
}
